def _get_or_create_genre(db: Session, name: str, order: int = 0) -> Genre:
    existing = db.scalar(select(Genre).where(Genre.name == name))
    if existing:
        return existing
    genre = Genre(name=name, display_order=order)
    db.add(genre)
    db.flush()
    return genre


def _get_or_create_tag(db: Session, name: str) -> Tag:
    existing = db.scalar(select(Tag).where(Tag.name == name))
    if existing:
        return existing
    tag = Tag(name=name)
    db.add(tag)
    db.flush()
    return tag


